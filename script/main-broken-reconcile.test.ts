import { describe, expect, test } from "bun:test"
import { chmodSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { delimiter, join } from "node:path"

const workflow = readFileSync(join(import.meta.dir, "..", ".github", "workflows", "main-broken.yml"), "utf8")

// The reconcile step's run-link collection lives between the RUN-LINKS
// markers so this fixture executes the exact shell the workflow runs,
// not a copy of it (#1314).
function snippet() {
  const begin = workflow.indexOf("# RUN-LINKS-BEGIN")
  const end = workflow.indexOf("# RUN-LINKS-END")
  expect(begin).toBeGreaterThan(-1)
  expect(end).toBeGreaterThan(begin)
  return workflow
    .slice(workflow.lastIndexOf("\n", begin) + 1, workflow.indexOf("\n", end))
    .split("\n")
    .map((line) => line.replace(/^ {12}/, ""))
    .join("\n")
}

// Stub `gh` views and capture the survivor comment generated by the workflow.
function reconcile(input: {
  readonly loser: number
  readonly survivor: number
  readonly body: string
  readonly comments: string
  readonly runID: number
}) {
  const dir = mkdtempSync(join(tmpdir(), "main-broken-reconcile-"))
  writeFileSync(join(dir, "body.txt"), input.body)
  writeFileSync(join(dir, "comments.txt"), input.comments)
  writeFileSync(
    join(dir, "gh"),
    [
      "#!/bin/sh",
      'if [ "$1" = issue ] && [ "$2" = comment ] && [ "$3" = "$SURVIVOR" ]; then',
      '  printf "%s" "$7" > "$FIXTURE_DIR/survivor-comment.txt"',
      "  exit 0",
      "fi",
      'case "$*" in',
      '  *"--json body"*) cat "$FIXTURE_DIR/body.txt" ;;',
      '  *"--json comments"*) cat "$FIXTURE_DIR/comments.txt" ;;',
      '  *"issue comment "*) ;;',
      '  *"issue close "*) ;;',
      '  *) echo "unexpected gh call: $*" >&2; exit 1 ;;',
      "esac",
      "",
    ].join("\n"),
  )
  chmodSync(join(dir, "gh"), 0o755)
  const proc = Bun.spawnSync(["bash", "-c", `set -euo pipefail\n${snippet()}`], {
    env: {
      ...process.env,
      PATH: `${dir}${delimiter}${process.env.PATH ?? ""}`,
      FIXTURE_DIR: dir,
      LOSER: String(input.loser),
      SURVIVOR: String(input.survivor),
      REPO: "developing-today/opencode",
      BID: "test-breakage",
      RUN_URL: run(input.runID),
      NOW: "2026-11-01T00:00:00Z",
    },
  })
  try {
    expect(proc.exitCode).toBe(0)
    return readFileSync(join(dir, "survivor-comment.txt"), "utf8")
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

const run = (id: number) => `https://github.com/developing-today/opencode/actions/runs/${id}`

describe("main-broken race-loser reconcile run links (#1314)", () => {
  test("staged three-watcher reconcile forwards inherited run links", () => {
    const first = reconcile({
      loser: 12,
      survivor: 11,
      body: `Main-tier workflow failed.\n- Run: ${run(112)}\n`,
      comments: "",
      runID: 111,
    })
    const second = reconcile({
      loser: 11,
      survivor: 10,
      body: `Main-tier workflow failed.\n- Run: ${run(111)}\n`,
      comments: first,
      runID: 110,
    })

    // The actual A→B survivor comment becomes B's prior comment for B→C.
    expect(second.match(/https:\/\/github\.com\/[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+\/actions\/runs\/[0-9]+/g)).toEqual([
      run(111),
      run(112),
      run(110),
    ])
  })

  test("a plain loser with no comments forwards its body run link", () => {
    const comment = reconcile({ loser: 22, survivor: 21, body: `- Run: ${run(222)}\n`, comments: "", runID: 223 })
    expect(comment).toContain(run(222))
  })

  test("adjacent Markdown links are collected as separate run URLs", () => {
    const comment = reconcile({
      loser: 32,
      survivor: 31,
      body: "",
      comments: `[one](${run(333)}),[two](${run(334)})`,
      runID: 335,
    })
    expect(comment.match(/https:\/\/github\.com\/[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+\/actions\/runs\/[0-9]+/g)).toEqual([
      run(333),
      run(334),
      run(335),
    ])
  })
})
